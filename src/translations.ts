// Función para obtener las traducciones del idioma actual
export function getTranslations(language: string = 'es') {
  return translations[language as keyof typeof translations] || translations.es;
}

// Función para obtener una traducción específica
export function t(key: string, language: string = 'es') {
  const trans = getTranslations(language);
  const keys = key.split('.');
  let result: any = trans;
  
  for (const k of keys) {
    result = result?.[k];
  }
  
  return result || key;
}